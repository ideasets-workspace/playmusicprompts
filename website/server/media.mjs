      const record = await readJson(join(folder, 'asset.json'));
      if (record.kind !== kind) return null;
      if (record.id !== id || record.file !== (kind === 'listening' ? 'audio.mp3' : 'audio.bin')) fail('STORAGE_UNSAFE');
