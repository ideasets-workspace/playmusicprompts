      if (lease.url_kind !== undefined && !['v4_signed','cdn_unsigned'].includes(lease.url_kind)) fail('UNSAFE_DELIVERY');
      if (isCdn && lease.url_expires_at !== null && lease.url_expires_at !== undefined) fail('UNSAFE_DELIVERY');
