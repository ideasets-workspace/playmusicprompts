(() => {
'use strict';
const P=window.PMP, APP=window.PMP_APP, D=window.PMPWorkerDialog;
const creating=new Set(['queued','submitting','pending','ingesting']);
const enhancing=new Set(['queued','running']);
const copy=value=>JSON.parse(JSON.stringify(value));
const canonical=value=>JSON.stringify(sort(value));
function sort(value){if(Array.isArray(value))return value.map(sort);if(value&&typeof value==='object')return Object.fromEntries(Object.keys(value).sort().map(k=>[k,sort(value[k])]));return value;}
let enhancement=null, latestCreate=null, admitting=false, polling=false, timer, disposed=false;
let currentView=null,createAttempt=null,enhanceAttempt=null;
let undo=P.storage.get('enhancementUndo',null);
const pendingKey='pmp.website.pending-enhancement';
function show(model,attempt=null){currentView={kind:model.kind,id:model.id,attempt};D.open(model);}
function update(model,attempt=null){
  if(!currentView||currentView.kind!==model.kind)return false;
  if(currentView.id===undefined){if(!attempt||currentView.attempt!==attempt)return false;}
  else if(currentView.id!==model.id)return false;
  if(model.id!==undefined)currentView.id=model.id;
  return D.update(model);
}

function enhanceModel(op){
  const done=op.status==='complete',failed=['failed','uncertain'].includes(op.status);
  const labels={admitting:['Sending your description','Waiting for our service to accept this request.'],queued:['Your description is in line','Your request is saved. The enhancement worker has not started yet.'],running:['Finding the words for your sound','The enhancement worker is waiting for the music service. It does not report intermediate progress.'],complete:['Your sound, more clearly described','Compare both versions. Your description changes only when you choose to use this version.'],failed:['Your description needs attention','Your original words are unchanged.'],uncertain:['The response could not be confirmed','Your original words are unchanged. This request will not be repeated automatically.']};
  const [title,message]=labels[op.status]||['Checking your description','Refresh this operation to get its current status.'];
  return {...op,originalRequest:op.request,request:op.dispatchRequest||op.request,kind:'enhance',title,message,steps:[
    {id:'request',label:'Request saved',state:op.id?'complete':'active',detail:op.id?'Your request has a saved operation ID.':'Waiting for an admission receipt.'},
    {id:'enhance',label:'Description enhancement',state:done?'complete':failed?'failed':op.status==='running'?'active':'pending',detail:done?'The service returned the rewritten description below.':failed?'No usable enhancement has been confirmed.':'Your selected sound settings accompany your original description.'},
    {id:'review',label:'Your review',state:done?'active':'pending',detail:'Choose the version you want to keep. No music is generated by Enhance.'}
  ],onApply:apply,onKeepOriginal:()=>P.toast('Your original description is unchanged.'),onClose:renderActivity};
}
function writePrompt(value){P.state.draft.prompt=value;const input=P.$('#prompt');if(input)input.value=value;P.saveDraft();P.autoSizePrompt?.();window.PMPControls.syncQuick();}
function apply(text,model){
  P.saveDraft();
  if(P.state.draft.prompt!==model.result.original)throw Error('Your description changed while Enhance was working. Keep your current words, or restore the original shown here before applying this version.');
  if(model.originalRequest&&canonical(window.PMPControls.payload(P.state.draft))!==canonical(model.originalRequest))throw Error('Your selected sound settings changed while Enhance was working. Enhance this updated brief before applying a version.');
  undo={original:model.result.original,enhanced:text,previousEnhance:copy(P.state.draft.prompt_enhance??null)};
  P.storage.set('enhancementUndo',undo);
  // This text has already been rewritten. Do not run enhancement a second time
  // when Create compiles the selected controls around the new base description.
  P.state.draft.prompt_enhance={...(P.state.draft.prompt_enhance||{}),enabled:false};
  writePrompt(text);renderActivity();P.toast('Enhanced description applied. Your sound settings are preserved.');
}
function undoEnhancement(){
  P.saveDraft();
  if(!undo||P.state.draft.prompt!==undo.enhanced){P.toast('Your description has changed since Enhance. Undo will not overwrite your new words.');return;}
  if(undo.previousEnhance===null)delete P.state.draft.prompt_enhance;else P.state.draft.prompt_enhance=copy(undo.previousEnhance);
  const original=undo.original;undo=null;P.storage.set('enhancementUndo',null);writePrompt(original);renderActivity();P.toast('Your original description is restored.');
}
function creationModel(job){
  const recoverable=(job.creation?.children?.map(child=>child.job)||[job]).filter(child=>['ingest_failed','partial'].includes(child.status));
  return {...job.workflow,summary:job.summary,assetsSummary:job.assetsSummary,creation:job.creation,
    ...(recoverable.length?{onRetry:async()=>{
      const connection=await APP.request('/api/connection');
      if(connection.delivery?.available!==true)throw Error('Saving is still paused. Our audio processing service needs to recover first. Your generation record is saved; no new generation was requested.');
      // Resume only these existing owned deliveries. Neither endpoint creates music.
      for(const child of recoverable)await APP.request('/api/jobs/'+encodeURIComponent(child.id)+'/retry-ingest',{method:'POST',body:{}});
      await APP.refreshJobs();const fresh=APP.jobs.find(item=>item.id===job.id);if(fresh)receiveCreate(fresh);
    }}:{}),
    onPlay:async track=>{const index=(job.tracks||[]).findIndex(item=>item.id===track.id);const s=P.queueCreation({...track,preparedTracks:index<0?[]:job.tracks.slice(index+1)});await P.playTrack(s.id,{keepDialog:true});},onClose:renderActivity};
}
function receiveCreate(job,attempt=null){
  if(!job?.workflow)return;
  if(!latestCreate||job.id===latestCreate.id||job.createdAt>latestCreate.createdAt)latestCreate=job;
  const model=creationModel(job);if(attempt)attempt.model=model;else if(createAttempt?.model.id===job.id)createAttempt.model=model;update(model,attempt);renderActivity();
}
function receiveEnhance(op,attempt=null){enhancement=op;const model=enhanceModel(op);if(attempt)attempt.model=model;update(model,attempt);renderActivity();}
function renderActivity(){
  const form=P.$('#composer');if(!form)return;
  let node=P.$('#workflow-activity');
  if(!node){node=document.createElement('div');node.id='workflow-activity';node.className='workflow-activity';form.append(node);}
  const buttons=[];
  const enhanceView=enhanceAttempt&&enhanceAttempt.model.id===undefined?enhanceAttempt.model:enhancement;
  const createView=createAttempt&&createAttempt.model.id===undefined?createAttempt.model:latestCreate?.workflow;
  if(enhanceView)buttons.push(`<button type="button" class="text-button" data-action="workflow-enhance-open">Enhance · ${P.esc({admitting:'Sending',queued:'In line',running:'Working',complete:'Review description',failed:'Needs attention',uncertain:'Check response'}[enhanceView.status]||'Check status')}</button>`);
  if(createView)buttons.push(`<button type="button" class="text-button" data-action="workflow-create-open" data-id="${P.esc(createView.id||'')}">Create · ${P.esc(createView.title||'View progress')}</button>`);
  if(undo&&P.state.draft.prompt===undo.enhanced)buttons.push('<button type="button" class="text-button" data-action="workflow-undo">Undo enhancement</button>');
  node.innerHTML=buttons.join('');node.hidden=!buttons.length;
  const button=P.$('[data-action="enhance"]');if(button){button.disabled=!APP.schemaAvailable;button.setAttribute('aria-label',admitting||enhancing.has(enhancement?.status)?'View enhancement progress':'Enhance');}
}
async function refreshEnhancements(){
  const {operations}=await APP.request('/api/enhancements');
  const next=operations.find(op=>enhancing.has(op.status))||operations[0];
  if(next)receiveEnhance(next);
  let pending;try{pending=JSON.parse(sessionStorage.getItem(pendingKey));}catch{}
  if(pending&&operations.some(op=>op.idempotencyKey===pending.id))sessionStorage.removeItem(pendingKey);
  return operations;
}
async function pollEnhance(){
  if(polling||disposed)return;polling=true;
  try{if(enhancement&&enhancing.has(enhancement.status)){
    const {operation}=await APP.request(`/api/enhancements/${encodeURIComponent(enhancement.id)}`);receiveEnhance(operation);
  }}catch(error){update({...enhanceModel(enhancement),message:'Connection interrupted. Your saved operation remains available; checking again shortly.'});}
  finally{polling=false;if(!disposed&&enhancing.has(enhancement?.status))timer=setTimeout(pollEnhance,3000);}
}
async function enhance(){
  if(admitting){show(enhanceAttempt.model,enhanceAttempt);return;}
  if(enhancing.has(enhancement?.status)){show(enhanceModel(enhancement));return;}
  P.saveDraft();let payload;
  try{payload=window.PMPControls.payload(P.state.draft);if(!payload.prompt?.trim())throw Error('Describe your sound first.');if(!APP.schemaAvailable)throw Error('The music service is not connected. Your description stays here.');}
  catch(error){P.toast(error.message);return;}
  const text=JSON.stringify(payload);let pending;
  try{pending=APP.readReceipt?APP.readReceipt(pendingKey):JSON.parse(sessionStorage.getItem(pendingKey));}catch(error){P.toast(error.message);return;}
  if(pending&&pending.payload!==text){
    try{await refreshEnhancements();pending=JSON.parse(sessionStorage.getItem(pendingKey));}catch{}
    if(pending){P.toast('An earlier enhancement submission needs to be reconciled. Restore that description or refresh activity before sending another request.');return;}
  }
  const id=pending?.id||crypto.randomUUID();
  sessionStorage.setItem(pendingKey,JSON.stringify({id,payload:text,authScope:APP.authScope}));
  admitting=true;const attempt=enhanceAttempt={model:enhanceModel({status:'admitting',request:copy(payload)})};show(attempt.model,attempt);renderActivity();
  try{
    const {operation}=await APP.request('/api/enhancements',{method:'POST',body:payload,headers:{'Idempotency-Key':id}});
    sessionStorage.removeItem(pendingKey);receiveEnhance(operation,attempt);clearTimeout(timer);pollEnhance();
  }catch(error){
    if(error.status&&error.status<500)sessionStorage.removeItem(pendingKey);
    attempt.model={...enhanceModel({status:error.status&&error.status<500?'failed':'uncertain',request:copy(payload)}),error:{message:error.message,contentSafety:error.contentSafety,quota:error.quota}};update(attempt.model,attempt);
  }finally{admitting=false;renderActivity();}
}
async function create(payload,options={}){
  if(window.PMPCreationContinuation?.clear()===false)throw Error('Allow site storage before starting a new creation. Your previous listening choice could not be cleared.');
  await window.PMPListening?.resetForCreation();
  await APP.refreshJobs?.();
  const active=APP.jobs.find(job=>creating.has(job.status));
  if(active){latestCreate=active;show(creationModel(active));throw Error('Your current creation is still running. Its progress is open.');}
  const attempt=createAttempt={model:{kind:'create',status:'admitting',title:'Sending your music brief',message:'Waiting for our service to accept this request.',request:copy(payload),steps:[{id:'request',label:'Save your request',state:'active',detail:'Your selected controls are shown below.'},{id:'music',label:'Music creation',state:'pending'},{id:'delivery',label:'Listening delivery',state:'pending'}],onClose:renderActivity}};
  show(attempt.model,attempt);renderActivity();
  try{return await APP.generate(payload,{...options,onAdmitted:job=>receiveCreate(job,attempt)});}
  catch(error){
    if(!attempt.model.id){const definite=error.status&&error.status<500;attempt.model={...attempt.model,status:definite?'failed':'uncertain',title:definite?'Request was not accepted':'Request outcome unconfirmed',message:error.message,error:{message:error.message,contentSafety:error.contentSafety,quota:error.quota},steps:attempt.model.steps.map((s,i)=>({...s,state:i===0?(definite?'failed':'unavailable'):'pending'}))};update(attempt.model,attempt);}
    else if(creating.has(attempt.model.status))update({...attempt.model,reconnecting:true,message:'Live waiting ended. Your saved creation remains available in activity; refresh to check its latest status.'},attempt);
    renderActivity();
    throw error;
  }
}
async function openCreate(id){
  if(!id&&createAttempt){show(createAttempt.model,createAttempt);return;}
  const job=APP.jobs.find(item=>item.id===id);if(!job?.workflow){P.toast('Refresh activity to load this creation.');return;}
  latestCreate=job;show(creationModel(job));renderActivity();
}
Object.assign(P.actions,{'workflow-enhance-open':()=>{if(enhanceAttempt?.model?.id===undefined&&enhanceAttempt)show(enhanceAttempt.model,enhanceAttempt);else if(enhancement)show(enhanceModel(enhancement));},'workflow-create-open':button=>openCreate(button.dataset.id),'workflow-undo':undoEnhancement});
P.pageHooks.push(renderActivity);
P.onInput.push(el=>{if(el.id==='prompt')renderActivity();});
window.addEventListener('pmp:jobs',()=>{for(const job of APP.jobs)receiveCreate(job);});
window.addEventListener('pmp:ready',()=>{refreshEnhancements().then(()=>pollEnhance()).catch(()=>{});for(const job of APP.jobs)receiveCreate(job);});
window.addEventListener('pagehide',()=>{disposed=true;clearTimeout(timer);},{once:true});
window.PMPWorkflow=Object.freeze({enhance,create,openCreate,refreshEnhancements});
})();
