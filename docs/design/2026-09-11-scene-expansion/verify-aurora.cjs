const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('C:/Berk/PlayMusicPrompts/docs/design/2026-09-09-html-mockups/tools/node_modules/playwright');
const folder = __dirname;
const source = fs.readFileSync(path.join(folder, 'aurora-asset.js'), 'utf8');
(async () => {
  const browser = await chromium.launch({ executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true, args:['--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport:{width:1200,height:900} });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if(message.type()==='error') errors.push(message.text()); });
  await page.route('**/aurora-verification', route => route.fulfill({contentType:'text/html',body:'<!doctype html><html><head><script type="importmap">{"imports":{"three":"/vendor/three/build/three.module.js","three/addons/":"/vendor/three/examples/jsm/"}}</script></head><body style="margin:0;background:#09090f"></body></html>'}));
  await page.goto('http://127.0.0.1:4173/aurora-verification');
  const report = await page.evaluate(async source => {
    const THREE = await import('three');
    const { EffectComposer } = await import('three/addons/postprocessing/EffectComposer.js');
    const { RenderPass } = await import('three/addons/postprocessing/RenderPass.js');
    const { UnrealBloomPass } = await import('three/addons/postprocessing/UnrealBloomPass.js');
    const { OutputPass } = await import('three/addons/postprocessing/OutputPass.js');
    const { createAuroraAsset } = await import(URL.createObjectURL(new Blob([source],{type:'text/javascript'})));
    const renderer = new THREE.WebGLRenderer({antialias:true,preserveDrawingBuffer:true});
    renderer.setSize(1200,900); renderer.setClearColor(0x09090f); renderer.toneMapping=THREE.ACESFilmicToneMapping;
    document.body.append(renderer.domElement);
    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera(38,1200/900,.1,100);
    camera.position.set(3.4,1.1,8.2); camera.lookAt(0,0,0);
    const asset = createAuroraAsset(THREE); scene.add(asset.group);
    const composer = new EffectComposer(renderer); composer.addPass(new RenderPass(scene,camera)); composer.addPass(new UnrealBloomPass(new THREE.Vector2(1200,900),.55,.65,.8)); composer.addPass(new OutputPass());
    asset.update({time:4,bass:.45,mid:.35,treble:.2,energy:.4,motion:true,intensity:.65});
    await renderer.compileAsync(scene,camera); renderer.render(scene,camera);
    const assetRender = {...renderer.info.render};
    composer.render();
    const materialState = () => JSON.stringify(asset.group.children.map(o=>Object.fromEntries(Object.entries(o.material.uniforms).map(([key,u])=>[key,u.value?.isColor?u.value.getHex():u.value]))));
    const before = materialState();
    asset.update({time:190,bass:1,mid:1,treble:1,energy:1,motion:false,intensity:.65});
    const frozen = before === materialState();
    const groups = asset.group.children.map(o=>({name:o.name,type:o.type,vertices:o.geometry.attributes.position.count,triangles:o.geometry.index?o.geometry.index.count/3:0,finitePositions:Array.from(o.geometry.attributes.position.array).every(Number.isFinite)}));
    asset.setPalette({light:0x4ae1a3,rim:0x74bce8,tint:0xb3e5cf});
    composer.render();
    window.__auroraTest = {asset,scene,camera,renderer,composer};
    return {three:THREE.REVISION,frozen,groups,shaderPrograms:renderer.info.programs.length,assetRender};
  },source);
  await page.screenshot({path:path.join(folder,'aurora-standalone-review.png')});
  report.shaderErrors = errors;
  report.disposed = await page.evaluate(()=>{const a=window.__auroraTest.asset;a.dispose();a.dispose();return a.group.children.length===0;});
  fs.writeFileSync(path.join(folder,'aurora-structural-checks.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
  await browser.close();
  if(errors.length||!report.frozen||!report.disposed||report.groups.some(g=>!g.finitePositions)) process.exitCode=1;
})().catch(error=>{console.error(error);process.exitCode=1;});
